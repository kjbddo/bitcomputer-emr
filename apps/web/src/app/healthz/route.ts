import { NextResponse } from "next/server";

/**
 * 컨테이너 오케스트레이터가 이 파드에 트래픽을 보내도 되는지 묻는 자리.
 *
 * **왜 필요한가.** compose 에는 frontend 헬스체크가 없어 `Up` 만 찍혔다.
 * 그래도 문제가 없던 것은 사람이 브라우저를 열어 확인했기 때문이다.
 * 쿠버네티스에는 그 사람이 없다 — `readinessProbe` 가 없으면 컨테이너
 * 프로세스가 뜨자마자 Service 엔드포인트에 등록되고 ALB 타깃이 healthy 로
 * 바뀐다. Next 가 아직 준비되지 않았는데 첫 요청들이 그리로 가서 실패한다.
 *
 * **왜 `/api` 밖에 있는가.** 배포에서 `/api/*` 는 ALB 가 조건 없이 Spring 으로
 * 보내고, 로컬에서는 next.config 의 rewrite 가 같은 일을 한다. 그 아래 두면 공개
 * 주소로 물었을 때 프론트가 아니라 Spring 이 답한다 — 프론트 상태를 묻는데 다른
 * 답이 오고, 200 이 나오므로 그것이 정상으로 보인다. readinessProbe 는 파드에
 * 직접 붙어 우연히 맞는데, 사람이 공개 URL 로 확인할 때만 어긋난다.
 *
 * **왜 `/login` 을 쓰지 않는가.** 200 은 뜨지만 그것이 무엇을 뜻하는지가
 * 흐리다. 로그인 페이지가 리다이렉트나 리브랜딩으로 바뀌면 프로브가 함께
 * 흔들리고, 실패했을 때 "화면이 깨진 것"인지 "서버가 안 뜬 것"인지 구별할 수
 * 없다. 프로브는 자기 자신 말고 아무것도 검사하지 않아야 한다.
 *
 * **무엇을 검사하지 않는가.** 상류(Spring·DB)를 확인하지 않는다. 상류가
 * 죽었다고 이 파드를 재시작하면 장애가 전파되고, 상류가 돌아와도 이쪽이
 * 재시작 루프에 빠져 있을 수 있다. 이 응답은 "이 프로세스가 요청을 처리할 수
 * 있다" 까지만 말한다.
 */
export const dynamic = "force-dynamic";

export function GET() {
  return NextResponse.json({ status: "ok" }, { status: 200 });
}
